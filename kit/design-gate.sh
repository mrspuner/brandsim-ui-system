# 8. двойники состояний [data-force] (UI-KIT.md → Требования
#    к коду). Страница кита показывает матрицу состояний: :hover и :focus
#    нельзя включить у двенадцати экземпляров разом, поэтому каждое правило
#    состояния записано как :is(псевдокласс, [data-force~="имя"]). Правило без
#    двойника — это ячейка матрицы, которая молча врёт: показывает обычное
#    состояние под заголовком «Наведение». Отсюда проверка.
#
#    Форма важна ровно так же, как в остальных проверках. Ищем НЕ построчно:
#    список селекторов переносится (label.field input:focus, label.field
#    select:focus — одна строка, но .sfield:has(...) .sf-track занимает две),
#    поэтому разбираем по блокам «всё до {». Комментарии снимаются ПЕРЕД
#    разбором: в styles.css есть комментарии, где :focus-visible упоминается
#    прозой (строка про outline:none у .icon-btn) — построчный grep честно
#    падал бы на них.
#
#    :disabled и :checked двойника НЕ требуют: это настоящие состояния
#    элемента, кит включает их свойством узла, а не атрибутом.
out8=$(python3 - <<'PYEOF' 2>&1
import re, sys

STATES = r":(?:hover|focus|focus-visible|focus-within|active)\b"
bad = []
for path in ("styles.css", "kit.css"):
    try:
        src = open(path, encoding="utf-8").read()
    except OSError as e:
        print(f"{path}: не прочитан: {e}")
        sys.exit(1)
    # снять комментарии, сохранив нумерацию строк
    stripped = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), src, flags=re.S)
    for m in re.finditer(r"([^{}]+)\{", stripped):
        sel = m.group(1)
        if not re.search(STATES, sel):
            continue
        if "data-force" in sel:
            continue
        line = stripped.count("\n", 0, m.start(1)) + 1
        bad.append(f"{path}:{line}: {' '.join(sel.split())}")
for b in bad:
    print(b)
PYEOF
)
rc8=$?
