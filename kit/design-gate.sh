# 9. инлайновый SVG мимо icons.js. Глифы живут в одном
#    модуле и вызываются функцией; разметка и скрипты своих <svg> не держат.
#    До общего модуля иконок разметка и три скрипта несли свои копии путей, и крестик в
#    ките уже расходился с крестиком в продукте на полтора десятых штриха.
#
#    Два исключения, и оба не иконки:
#      radar.js   — рисует диаграмму через svgEl(), это графика данных;
#      index.html — фавикон в data:-URI, это продуктовый знак, а не иконка интерфейса.
#    Фавикон сидит в строке с rel="icon" — по ней и отсеивается, а не по номеру
#    строки: номер съедет от первой же правки выше.
#
#    Ловим именно ГЛИФ, а не всякое упоминание SVG: первая редакция
#    этой проверки честно падала на svgEl() в ui.js — общем помощнике, через
#    который radar.js рисует диаграмму, и на строке-сниппете в ките, которая
#    вообще текст для копирования. Признак глифа другой: литеральные данные
#    контура — d="M…" или d: "M…" — либо целый <svg> строкой в разметке.
#    Сразу грабли на будущее, чтобы не наступить дважды: bash внутри $( … )
#    считает одинарные кавычки В ТЕЛЕ heredoc, хотя тот закавычен как
#    <<\'PYEOF\'. Нечётное число апострофов — и весь файл падает с unexpected EOF
#    на строке, которая к ошибке отношения не имеет. У проверки 8 они сошлись
#    чётно случайно. Здесь одинарных кавычек нет вовсе: в регулярке они записаны
#    кодами \\x22 и \\x27.
out9=$(python3 - <<'PYEOF' 2>&1
import re, glob, sys

GLYPH = re.compile(r"\\bd\\s*[:=]\\s*[\\x22\\x27]\\s*[Mm][\\d.\\-]")
RAWSVG = re.compile(r"<svg[\s>]")
bad = []
for path in sorted(glob.glob("*.html") + glob.glob("*.js")):
    if path == "icons.js":
        continue
    try:
        src = open(path, encoding="utf-8").read()
    except OSError as e:
        print(f"{path}: \u043d\u0435 \u043f\u0440\u043e\u0447\u0438\u0442\u0430\u043d: {e}")
        sys.exit(1)
    for i, line in enumerate(src.split("\n"), 1):
        if "rel=" in line and "icon" in line:
            continue
        if GLYPH.search(line) or RAWSVG.search(line):
            bad.append(f"{path}:{i}: {line.strip()[:90]}")
for b in bad:
    print(b)
PYEOF
)
rc9=$?
report_rc "9. инлайновый SVG мимо icons.js" "$rc9" "$out9"


