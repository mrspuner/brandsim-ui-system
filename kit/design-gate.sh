#!/usr/bin/env bash
# design-gate.sh — гейт приёмки по дизайн-системе (DESIGN.md, правило 5 в CLAUDE.md).
#
# Задача 12 закрыла долг о том, что этот гейт жил только строчками в
# отчётах задач: шаблоны grep'ов терялись между задачами, а расширение на
# index.html (где однажды нашёлся синий фавикон, и это уже повторялось
# дважды до этого) не было закреплено нигде, кроме .gitignore'нутого
# отчёта. Теперь гейт — файл в репозитории, а не текст, который умирает
# вместе с рабочим каталогом агента.
#
# ВАЖНО, прочитать перед тем как добавлять новую проверку: index.html несёт
# SVG в `data:` URI (фавикон), где `#`/`<`/`>` percent-encoded (`%23`/`%3C`/
# `%3E`). Первая версия этого гейта проверяла синий строкой `#2f6feb` и
# честно проходила «зелёной» на файле, где сидело `%232f6feb`, — тот самый
# фавикон, ради которого гейт вообще писался. Решение — не подбирать
# альтернативы под каждый шаблон отдельно, а один раз URL-декодировать файл
# ПЕРЕД любой проверкой (см. DECODE_DIR ниже): тогда проверки видят ровно
# то, что видит браузер, а не то, что буквально лежит в файле. Любая новая
# проверка обязана либо читать из декодированной копии, либо явно
# аргументировать, почему кодировка ей не грозит.
#
# ВТОРОЕ ПРАВИЛО, того же происхождения (найдено при повторном ревью:
# id брендов проверялись через подчёркивание вместо дефиса — данные
# продукта дают `nordika-aura`, не `nordika_aura`; синий не ловился
# через rgba() — только через rgb()). Каждая проверка обязана ловить
# нарушение в ТОЙ ФОРМЕ, в какой оно реально встречается в этом проекте —
# не в форме, придуманной по аналогии с похожим и удобной для regex'а.
# Источник истины у каждой проверки свой и внешний по отношению к этому
# файлу: id брендов — данные продукта, а не память о том, как их называли
# в постановке; следы сторонних инструментов — их исходники, а не
# воспоминание о том, как выглядел похожий маркер; цвета — то, как
# они реально записаны в styles.css (hex, rgb(), rgba(), percent-encoded
# внутри data: URI), а не один из вариантов записи. Где нарушение реально
# встречалось в этом репозитории — проверять на нём же (git show), не на
# похожем. Где не встречалось — брать форму из источника, который его
# порождает, а не сочинять правдоподобную.
#
# Что проверяет и, для каждой, В КАКОЙ ФОРМЕ нарушение реально встречается
# в этом проекте (не «что» — это тривиально, а «как записано», потому что
# именно на разнице между «как записано» и «как ожидал шаблон» гейт
# спотыкался девять раз подряд за три раунда ревью):
#   1. hex мимо токенов дизайн-системы. Формы: styles.css — hex вне
#      единственного объявления "--name: #hex;" на своей строке (не «вне
#      строки, начинающейся на --» — вторая строка ловится, только если
#      декларация НЕ единственное, что на ней есть); index.html/*.js — hex,
#      НЕ совпадающий со значением реального токена (совпадающий печатается
#      как известный, не проваливает — данные внутри data:-URI не могут
#      сослаться на var()).
#   2. синий в любом виде (The No Blue Rule). Формы: hex (#2f6feb — старый
#      фавикон; #5b8cf5 — --accent старой тёмной темы), rgb(), rgba()
#      с пробелами и без — весь styles.css пишет rgba(), а не rgb().
#   3. следы тёмной темы. Форма: подстрока "prefers-color-scheme" в любом
#      регистре (CSS регистронезависим для имён медиа-фич).
#   5. id брендов вида nordika-aura в интерфейсе (только имена через
#      brandName). Форма — дефис, не подчёркивание (как id записаны в данных продукта).
#   7. синий среди ОБЪЯВЛЕННЫХ ТОКЕНОВ — та же форма, что и в проверке 2,
#      но в строке, которую проверка 1 намеренно пропускает как чистое
#      объявление токена. «Легитимно объявленный» и «не синий» — разные
#      утверждения; критерий один и тот же (is_blue у проверки 2), второго
#      разборщика цвета в файле нет.
#   6. старые числа ширины рабочей области — отдельно «должно быть пусто»
#      (1240/1300/1302/1252 — вытесненные значения) и отдельно «известная
#      контрольная точка» (1250 — порог двухоконного режима,
#      выведен из реальных размеров карточки и обязан жить ровно в одном
#      месте, в styles.css). Смешивать эти два случая в одну проверку
#      нельзя: гейт, который на любой вход даёт один и тот же результат,
#      отучает читать вывод. Форма — число с суффиксом "px" (CSS-длина;
#      без суффикса эти же цифры реально встречаются в проекте не по
#      адресу — см. комментарий у 6a/6b).
#
# Проверяет ВСЕ файлы фронта (index.html, styles.css, *.js), а не только
# styles.css — предыдущая версия гейта смотрела только в styles.css, и
# именно поэтому синий в index.html дважды проходил незамеченным.
#
# Запуск:            bash design-gate.sh   (или ./design-gate.sh)
# Код возврата:       0 — гейт пройден; N > 0 — упало N проверок из десяти
#                      (1, 2, 3, 5, 6a, 6b, 7, 8, 9, 10; номер 4 у исходного
#                      продукта проверял следы инструментов, здесь не нужен) — какие именно,
#                      видно в выводе. Сбой самого инструмента (python3
#                      вернул ненулевой код, декодирование не выполнилось) —
#                      это тоже FAIL, а не «ok»: проверка, которой не было,
#                      не считается пройденной.
#                      Мерить БЕЗ пайпа (bash design-gate.sh; echo $?) —
#                      через `| tail`/`| grep` вернётся код читающей команды,
#                      не гейта.
# Использование перед коммитом: `bash design-gate.sh && git commit …` —
# ненулевой код останавливает конвейер.

set -uo pipefail
cd "$(dirname "$0")"

fail=0

report() { # report <label> <output>
  local label="$1" out="$2"
  if [ -n "$out" ]; then
    echo "FAIL — $label"
    echo "$out"
    fail=$((fail + 1))
  else
    echo "ok   — $label"
  fi
}

# report_rc <label> <код возврата инструмента> <output>
# Пустой вывод сам по себе НЕ доказательство чистоты: у проверок 1, 2 и 7
# вывод собирает python3, и при любом его сбое (нет интерпретатора, ошибка
# в heredoc'е, исключение на нечитаемом файле) stdout пуст, stderr уходит
# мимо, а report() печатал "ok". Гейт зеленел ровно там, где проверка не
# выполнялась — режим отказа хуже отсутствия гейта: отчёт о проверке,
# которой не было. Код возврата разбирается явно и превращается в FAIL.
report_rc() { # report_rc <label> <rc> <output>
  local label="$1" rc="$2" out="$3"
  if [ "$rc" -ne 0 ]; then
    echo "FAIL — $label"
    echo "     проверка НЕ ВЫПОЛНЕНА: python3 завершился с кодом $rc (вывод ниже, если был)"
    [ -n "$out" ] && echo "$out"
    fail=$((fail + 1))
    return
  fi
  report "$label" "$out"
}

shopt -s nullglob
JS_FILES=(*.js)
# Страница кита — такой же фронт, как экраны, и обязана проходить те же
# проверки. В исходном продукте здесь стоял и index.html экранов; в этом
# репозитории экранов нет, поэтому HTML — только kit.html. Упоминания
# index.html в комментариях ниже — история того, зачем проверка появилась.
HTML_FILES=(kit.html)
ALL_FILES=("${HTML_FILES[@]}" styles.css kit.css "${JS_FILES[@]}")
SELF="$(basename "$0")"

echo "== гейт приёмки: $(pwd) =="
echo

# --- декодирование percent-encoding перед любой проверкой -----------------
# Для файлов без "%XX" декодирование — no-op (проверено: сейчас единственный
# такой файл в исходном продукте — index.html с фавиконом в data:-URI).
# Проверки 1/2/3/5/6 читают из DECODE_DIR, а не из рабочих файлов напрямую.
DECODE_DIR="$(mktemp -d)"
trap 'rm -rf "$DECODE_DIR"' EXIT
DECODE_FAILED=""
for f in "${ALL_FILES[@]}"; do
  # Раньше здесь стояло "|| cp" без единого слова в выводе: при сломанном
  # python3 проверки 1/2/3/5/6/7 тихо теряли декодирование и продолжали
  # печатать "ok" — то есть percent-encoded синий (ровно тот фавикон, ради
  # которого гейт написан) снова становился невидимым. Падение теперь
  # называется вслух и проваливает гейт; сырая копия всё же кладётся, чтобы
  # остальные проверки успели показать, что видят.
  if ! python3 -c '
import sys, urllib.parse
with open(sys.argv[1], encoding="utf-8") as fh:
    data = fh.read()
sys.stdout.write(urllib.parse.unquote(data))
' "$f" > "$DECODE_DIR/$f" 2>/dev/null; then
    cp "$f" "$DECODE_DIR/$f"
    DECODE_FAILED="$DECODE_FAILED $f"
  fi
done
if [ -n "$DECODE_FAILED" ]; then
  echo "FAIL — 0. декодирование percent-encoding"
  echo "     не удалось декодировать:$DECODE_FAILED — проверки 1/2/3/5/6/7 идут по сырым файлам"
  echo
  fail=$((fail + 1))
fi
D() { printf '%s/%s' "$DECODE_DIR" "$1"; }               # decoded path for a file
strip_tmp() { sed "s#$DECODE_DIR/##"; }                  # вернуть читаемые имена в выводе

DEC_JS_FILES=()
for f in "${JS_FILES[@]}"; do DEC_JS_FILES+=("$(D "$f")"); done
DEC_ALL_FILES=("$(D kit.html)" "$(D styles.css)" "$(D kit.css)" "${DEC_JS_FILES[@]}")

# 1. hex мимо токенов. В styles.css легитимны только строки, целиком
#    состоящие из одного объявления "--name: #hex;" и ничего больше — не
#    «строка содержит "--" где-то», а именно строка ЦЕЛИКОМ, включая
#    хвостовые комментарии. Раньше проверка исключала любую строку,
#    начинающуюся на "--", grep'ом по ЦЕЛОЙ СТРОКЕ — а значит хардкод,
#    дописанный на ту же строку ПОСЛЕ легитимного токена (второе
#    объявление, или hex в хвостовом комментарии), молча исчезал вместе с
#    ней. Первая правка эту дыру не закрыла до конца: decl_re сам разрешал
#    необязательный хвостовый комментарий, и `--paper: #ffffff; /* см.
#    #123abc */` по-прежнему проходила чисто (проверено, поймано на
#    собственном тесте). Комментарий на той же строке, что и объявление,
#    теперь вообще не considered «чистым» — реальных таких строк в
#    styles.css сейчас нет, переносить пояснение на отдельную строку не
#    в тягость. В index.html/*.js токенов не объявляют вовсе, но data-URI
#    фавикона физически не может сослаться на var(--token) — поэтому там
#    сверяем не «есть хоть один hex», а «совпадает ли он со значением
#    реального токена»: совпал — известное, ожидаемое повторение
#    (печатается, не проваливает проверку); не совпал — настоящий
#    хардкод, падает.
CHECK1_OUT="$(python3 - "$(D styles.css)" "$(D kit.html)" "$(D kit.css)" "${DEC_JS_FILES[@]}" <<'PYEOF'
import re, sys

styles_path = sys.argv[1]
other_paths = sys.argv[2:]
hex_re = re.compile(r'#[0-9a-fA-F]{3,8}')
# Строка целиком — одно объявление токена и больше НИЧЕГО (ни второго
# значения, ни хвостового комментария — комментарий может прятать чужой
# hex так же, как второе объявление).
decl_re = re.compile(r'^\s*--[A-Za-z0-9-]+\s*:\s*#[0-9a-fA-F]{3,8}\s*;?\s*$')

with open(styles_path, encoding="utf-8") as fh:
    styles_lines = fh.readlines()

root_start = root_end = None
for i, line in enumerate(styles_lines):
    if line.startswith(":root"):
        root_start = i
    elif root_start is not None and line.startswith("}"):
        root_end = i
        break
tokens = set()
if root_start is not None and root_end is not None:
    for line in styles_lines[root_start:root_end]:
        if decl_re.match(line):
            for m in hex_re.finditer(line):
                tokens.add(m.group(0).lower())

violations, known = [], []
for i, line in enumerate(styles_lines, 1):
    if decl_re.match(line):
        continue  # чистое одиночное объявление токена — не трогаем
    for m in hex_re.finditer(line):
        violations.append(f"styles.css:{i}: {m.group(0)}")

for path in other_paths:
    with open(path, encoding="utf-8") as fh:
        for i, line in enumerate(fh, 1):
            for m in hex_re.finditer(line):
                hx = m.group(0).lower()
                tag = f"{path}:{i}: {m.group(0)}"
                if hx in tokens:
                    known.append(tag + " (совпадает со значением токена — ожидаемо для data-URI, где var() недоступен)")
                else:
                    violations.append(tag)

print("===VIOLATIONS===")
for v in violations:
    print(v)
print("===KNOWN===")
for k in known:
    print(k)
PYEOF
)"
CHECK1_RC=$?
CHECK1_OUT="$(printf '%s' "$CHECK1_OUT" | strip_tmp)"
out1=$(printf '%s\n' "$CHECK1_OUT" | sed -n '/===VIOLATIONS===/,/===KNOWN===/p' | sed '1d;$d' | sed '/^$/d')
out1known=$(printf '%s\n' "$CHECK1_OUT" | sed -n '/===KNOWN===/,$p' | sed '1d' | sed '/^$/d')
report_rc "1. hex мимо токенов" "$CHECK1_RC" "$out1"
if [ -n "$out1known" ]; then
  echo "     известные (не проваливают проверку):"
  printf '%s\n' "$out1known" | sed 's/^/     /'
fi

# 2. синий в любом виде — по декодированным файлам фронта, включая
#    index.html (там и сидел синий фавикон, закодированный как %232f6feb —
#    буквальный поиск "#2f6feb" его не видел).
#    Формы, в которых синий реально встречался/встречается в этом проекте:
#      - hex: #2f6feb, #5b8cf5 (--accent тёмной темы,
#        git show 0b2fdd6) — ловятся буквальным совпадением, они известны
#        поимённо;
#      - rgb()/rgba(), с пробелами после запятых и без — styles.css СЕЙЧАС
#        весь на rgba() (--ink-veil, --shadow-panel, --scrim, --paper-veil,
#        --line-veil) — не гипотетическая форма, а способ, которым в этом
#        файле вообще пишут цвет. Первая правка проверяла «есть ли где-то
#        внутри скобок трёхзначное число, начинающееся на 2» — грубая
#        привязка к цифре, а не к цвету: rgba(255, 255, 255, .72)
#        (--paper-veil, самый обычный белый) тоже содержит «255», три числа
#        подряд, «2XX» находится и там — ложное срабатывание на реальном,
#        ничем не примечательном токене. И тот же класс дыры, что уже был
#        (id брендов ловились только с подчёркиванием, rgba не ловился
#        через rgb) — шаблон совпадал с формой цифр, а не со смыслом
#        «это синий». Заменено на разбор самих RGB-каналов (ниже, python):
#        синий канал заметно выше красного и зелёного — было ложным на
#        белом/сером/чёрном (все три канала равны или близки), ловит
#        rgb(47,111,235) и rgba(47, 111, 235, 1) (канал синего 235 против
#        47 и 111 — явный перекос в синий), не ловит rgba(255,255,255,…)/
#        rgba(32,32,32,…)/rgba(0,0,0,…)/rgba(7,6,7,…) — все реальные
#        текущие токены styles.css.
#    Разбор цвета один на весь гейт (is_blue ниже): его же переиспользует
#    проверка 7 для hex'ов, объявленных токенами. Второго критерия «это
#    синий» в файле нет и быть не должно — два критерия неизбежно разъедутся,
#    и разъедутся молча.
COLOR_OUT="$(python3 - "${DEC_ALL_FILES[@]}" <<'PYCOLOR'
import re, sys

# Единственный на весь гейт критерий «это синий»: ТОН, а не перекос каналов.
#
# Через перекос каналов критерий писался дважды и оба раза был неверен.
# Абсолютный порог (b >= 180) пропускал тёмный сине-серый — ровно то, чем
# был написан скрим модального окна rgba(20, 26, 40, .45): синева видна
# глазом, а синий канал всего 40. Относительный порог (b > r + 24) не
# пропускал его тоже — 40 против 20+24 — и при этом стоял в одном шаге от
# ложного срабатывания на легитимном chart-violet (#7a3f91, синий 145 против
# красного 122: разница 23 при пороге 24). Порог, который одновременно ловит
# тёмную синеву и не задевает фиолетовый, через каналы не подбирается: это
# два разных ТОНА, а не два разных перекоса.
#
# Тон разделяет их без всякой подгонки. Синий занимает 200-260° цветового
# круга, фиолетовый начинается за 270°. Насыщенность отсекает серое: у
# чистого серого тон не определён и вычисляется в мусор.
#
# Проверено на всей палитре: все десять chart-* проходят (фиолетовый
# 283°, орхидея 314°, жад 158°), Ember 19° проходит, бумага 0%/серые
# проходят по насыщенности; скрим модалки 222° и типовой синий #3b5bdb
# 228° — валятся.
BLUE_HUE_LO, BLUE_HUE_HI, GREY_SAT = 200.0, 260.0, 15.0

def is_blue(r, g, b):
    h, s = _hue_sat(r, g, b)
    return BLUE_HUE_LO <= h <= BLUE_HUE_HI and s >= GREY_SAT

def _hue_sat(r, g, b):
    """Тон в градусах и насыщенность в процентах (HSL)."""
    import colorsys
    h, _l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    return h * 360, s * 100

def hex_channels(text):
    h = text.lstrip("#")
    if len(h) in (3, 4):
        h = "".join(c * 2 for c in h[:3])
    elif len(h) in (6, 8):
        h = h[:6]
    else:
        return None
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))

# Формы записи цвета. Прежняя версия знала ровно одну — rgb() через запятые
# с целыми числами — и пропускала три остальные, которые браузер понимает
# одинаково: пробелы вместо запятых, проценты вместо чисел, hsl() и
# именованные цвета. Тот же класс дыры, что и все предыдущие: шаблон
# совпадал с формой записи, а не со смыслом «это синий».
_NUM = r'([0-9]{1,3}(?:\.[0-9]+)?%?)'
_SEP = r'\s*[,\s]\s*'
rgb_re = re.compile(r'rgba?\(\s*' + _NUM + _SEP + _NUM + _SEP + _NUM)
hsl_re = re.compile(
    r'hsla?\(\s*(-?[0-9]{1,3}(?:\.[0-9]+)?)(?:deg)?' + _SEP
    + r'([0-9]{1,3}(?:\.[0-9]+)?)%' + _SEP + r'([0-9]{1,3}(?:\.[0-9]+)?)%')

def _chan(text):
    """Канал rgb(): «65%» и «166» — одно и то же значение."""
    return round(float(text[:-1]) * 255 / 100) if text.endswith("%") else int(text)

# Именованные цвета CSS, попадающие в синий диапазон тона. Список закрытый:
# в CSS их конечное число, и проверять весь справочник ради полноты дороже,
# чем перечислить те, что реально пишут руками.
NAMED_BLUES = {
    "navy": (0, 0, 128), "blue": (0, 0, 255), "mediumblue": (0, 0, 205),
    "darkblue": (0, 0, 139), "royalblue": (65, 105, 225),
    "steelblue": (70, 130, 180), "dodgerblue": (30, 144, 255),
    "cornflowerblue": (100, 149, 237), "slateblue": (106, 90, 205),
    "midnightblue": (25, 25, 112), "darkslateblue": (72, 61, 139),
    "lightskyblue": (135, 206, 250), "deepskyblue": (0, 191, 255),
    "skyblue": (135, 206, 235), "lightsteelblue": (176, 196, 222),
    "cadetblue": (95, 158, 160), "powderblue": (176, 224, 230),
}
named_re = re.compile(r'\b(' + "|".join(sorted(NAMED_BLUES, key=len, reverse=True)) + r')\b', re.I)
# то же определение «чистого объявления токена», что и в проверке 1: строка
# целиком — одно "--name: #hex;" и ничего больше
decl_re = re.compile(r'^\s*(--[A-Za-z0-9-]+)\s*:\s*(#[0-9a-fA-F]{3,8})\s*;?\s*$')

# Палитра радара:
# синий допустим ТОЛЬКО как значение токена конкурента на радаре. Исключение
# по имени токена целиком: строка должна объявлять --color-base-chart-rival-*.
# Синий в любом другом токене, в rgb()/hsl(), по имени или в radar.js —
# по-прежнему FAIL.
RIVAL_BLUE_OK = "--color-base-chart-rival-"
rgb_hits, token_hits = [], []
for path in sys.argv[1:]:
    with open(path, encoding="utf-8") as fh:
        for i, line in enumerate(fh, 1):
            for m in rgb_re.finditer(line):
                r, g, b = (_chan(x) for x in m.groups())
                if is_blue(r, g, b):
                    rgb_hits.append(
                        f"{path}:{i}: {m.group(0)} — тон {_hue_sat(r, g, b)[0]:.0f}° в синем диапазоне")
            for m in hsl_re.finditer(line):
                hue, sat = float(m.group(1)) % 360, float(m.group(2))
                if BLUE_HUE_LO <= hue <= BLUE_HUE_HI and sat >= GREY_SAT:
                    rgb_hits.append(
                        f"{path}:{i}: {m.group(0)} — тон {hue:.0f}° в синем диапазоне")
            for m in named_re.finditer(line):
                r, g, b = NAMED_BLUES[m.group(1).lower()]
                if is_blue(r, g, b):
                    rgb_hits.append(
                        f"{path}:{i}: {m.group(1)} — именованный синий, тон {_hue_sat(r, g, b)[0]:.0f}°")
            decl = decl_re.match(line)
            if decl and not decl.group(1).startswith(RIVAL_BLUE_OK):
                channels = hex_channels(decl.group(2))
                if channels and is_blue(*channels):
                    r, g, b = channels
                    token_hits.append(
                        f"{path}:{i}: {decl.group(1)}: {decl.group(2)} — тон {_hue_sat(r, g, b)[0]:.0f}° в синем диапазоне")

print("===RGB===")
for hit in rgb_hits:
    print(hit)
print("===TOKENS===")
for hit in token_hits:
    print(hit)
PYCOLOR
)"
